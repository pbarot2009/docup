/// HighlightCode renders source code as HTML with <span> tags marking
/// syntax categories (keyword, type, string, comment, number).
pub fn highlight_code(source: &str, lang: &str) -> String {
    let (profile, _) = get_profile(lang);
    highlight_with_profile(source, &profile)
}

fn highlight_with_profile(src: &str, prof: &LanguageProfile) -> String {
    let mut out = String::with_capacity(src.len() * 2);
    let chars: Vec<char> = src.chars().collect();
    let n = chars.len();
    let mut i = 0;

    let flush_span = |out: &mut String, class: &str, text: &str| {
        if text.is_empty() {
            return;
        }
        if class.is_empty() {
            escape_html_into(text, out);
        } else {
            out.push_str("<span class=\"tok-");
            out.push_str(class);
            out.push_str("\">");
            escape_html_into(text, out);
            out.push_str("</span>");
        }
    };

    while i < n {
        let c = chars[i];

        // 1. Block comments
        if let Some((start_tok, end_tok)) = prof.block_comment {
            if has_prefix_at(&chars, i, start_tok) {
                let start = i;
                let start_chars_len = start_tok.chars().count();
                let end_chars_len = end_tok.chars().count();
                i += start_chars_len;
                while i < n && !has_prefix_at(&chars, i, end_tok) {
                    i += 1;
                }
                if i < n {
                    i += end_chars_len;
                }
                let comment_text: String = chars[start..i].iter().collect();
                flush_span(&mut out, "comment", &comment_text);
                continue;
            }
        }

        // 2. Line comments
        let mut matched_comment = false;
        for &lc in prof.line_comments {
            if has_prefix_at(&chars, i, lc) {
                let start = i;
                while i < n && chars[i] != '\n' {
                    i += 1;
                }
                let comment_text: String = chars[start..i].iter().collect();
                flush_span(&mut out, "comment", &comment_text);
                matched_comment = true;
                break;
            }
        }
        if matched_comment {
            continue;
        }

        // 3. String literals
        if c == '"' || (prof.single_quote && c == '\'') || (prof.backtick && c == '`') {
            let quote = c;
            let start = i;
            i += 1;
            while i < n && chars[i] != quote {
                if chars[i] == '\\' && i + 1 < n {
                    i += 2;
                    continue;
                }
                i += 1;
            }
            if i < n {
                i += 1;
            }
            let string_text: String = chars[start..i].iter().collect();
            flush_span(&mut out, "string", &string_text);
            continue;
        }

        // 4. Numbers
        if is_digit_rune(c) {
            let start = i;
            while i < n
                && (is_digit_rune(chars[i])
                    || chars[i] == '.'
                    || chars[i] == '_'
                    || chars[i] == 'x'
                    || chars[i] == 'X'
                    || chars[i] == 'b'
                    || chars[i] == 'B'
                    || chars[i] == 'o'
                    || chars[i] == 'O'
                    || is_hex_digit_rune(chars[i]))
            {
                // Prevent multi-period range expressions (e.g. 1..10) from being consumed as a single number
                if chars[i] == '.' && i + 1 < n && chars[i + 1] == '.' {
                    break;
                }
                i += 1;
            }
            let num_text: String = chars[start..i].iter().collect();
            flush_span(&mut out, "number", &num_text);
            continue;
        }

        // 5. Identifiers, keywords, types
        let is_start = is_ident_start_rune(c)
            || (prof.allow_at_ident && c == '@' && i + 1 < n && is_ident_start_rune(chars[i + 1]))
            || (prof.allow_dollar_ident
                && c == '$'
                && i + 1 < n
                && (is_ident_start_rune(chars[i + 1]) || is_digit_rune(chars[i + 1])));

        if is_start {
            let start = i;
            i += 1;
            while i < n {
                let ch = chars[i];
                if is_ident_cont_rune(ch) {
                    i += 1;
                } else if prof.allow_hyphen_ident
                    && ch == '-'
                    && i + 1 < n
                    && is_ident_cont_rune(chars[i + 1])
                {
                    i += 1;
                } else if prof.allow_hyphen_ident && (ch == '!' || ch == '?') {
                    i += 1;
                    break;
                } else {
                    break;
                }
            }
            let word: String = chars[start..i].iter().collect();

            let is_keyword = if prof.ignore_case {
                prof.keywords.iter().any(|k| k.eq_ignore_ascii_case(&word))
            } else {
                prof.keywords.contains(&word.as_str())
            };

            let is_type = if prof.ignore_case {
                prof.types.iter().any(|t| t.eq_ignore_ascii_case(&word))
            } else {
                prof.types.contains(&word.as_str())
            };

            if is_keyword {
                flush_span(&mut out, "keyword", &word);
            } else if is_type {
                flush_span(&mut out, "type", &word);
            } else {
                flush_span(&mut out, "", &word);
            }
            continue;
        }

        // 6. Pass-through punctuation / whitespace
        let s = c.to_string();
        flush_span(&mut out, "", &s);
        i += 1;
    }

    out
}

fn has_prefix_at(chars: &[char], pos: usize, prefix: &str) -> bool {
    let prefix_chars: Vec<char> = prefix.chars().collect();
    if pos + prefix_chars.len() > chars.len() {
        return false;
    }
    chars[pos..pos + prefix_chars.len()] == prefix_chars[..]
}

#[inline]
fn is_digit_rune(c: char) -> bool {
    c.is_ascii_digit()
}

#[inline]
fn is_hex_digit_rune(c: char) -> bool {
    c.is_ascii_hexdigit()
}

#[inline]
fn is_ident_start_rune(c: char) -> bool {
    c == '_' || c.is_ascii_alphabetic()
}

#[inline]
fn is_ident_cont_rune(c: char) -> bool {
    is_ident_start_rune(c) || is_digit_rune(c)
}

/// Escapes HTML characters `<, >, &, ", '` directly into the destination buffer.
pub fn escape_html_into(s: &str, out: &mut String) {
    for c in s.chars() {
        match c {
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            '"' => out.push_str("&quot;"),
            '\'' => out.push_str("&#39;"),
            _ => out.push(c),
        }
    }
}

pub fn escape_html(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    escape_html_into(s, &mut out);
    out
}
